import { prefs } from "./state.js";

const PREF_TO_CODE = {
  Nederlands: "nl", English: "en", Deutsch: "de", "Français": "fr", "Español": "es",
};
export const LOCALES = { nl: "nl-NL", en: "en-US", de: "de-DE", fr: "fr-FR", es: "es-ES" };

export function uiLang() {
  if (prefs.language !== "auto") return PREF_TO_CODE[prefs.language] || "en";
  const b = (navigator.language || "nl").slice(0, 2).toLowerCase();
  return DICT[b] ? b : "en";
}

export function uiLocale() { return LOCALES[uiLang()] || "nl-NL"; }

export function t(key, vars) {
  const lang = uiLang();
  let s = DICT[lang]?.[key] ?? DICT.en[key] ?? DICT.nl[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}

// Zoals t(), maar voor lijst-waarden (bijv. de roterende hero-zinnen). Valt terug
// op EN/NL en geeft altijd een array terug.
export function tList(key) {
  const lang = uiLang();
  const v = DICT[lang]?.[key] ?? DICT.en[key] ?? DICT.nl[key];
  return Array.isArray(v) ? v : [];
}

